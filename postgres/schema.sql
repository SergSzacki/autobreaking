CREATE TABLE car (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    make        VARCHAR(255) NOT NULL,
    model       VARCHAR(255) NOT NULL,
    year        INTEGER NOT NULL CHECK (year BETWEEN 1886 AND 2200),
    vin         VARCHAR(17),
    mileage     INTEGER NOT NULL DEFAULT 0 CHECK (mileage >= 0),
    color       VARCHAR(100),
    status      VARCHAR(50) NOT NULL DEFAULT 'available',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_car_vin
    ON car (vin)
    WHERE vin IS NOT NULL;

CREATE TABLE part (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    category     VARCHAR(100),
    sku          VARCHAR(100),
    quantity     INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    min_quantity INTEGER NOT NULL DEFAULT 0 CHECK (min_quantity >= 0),
    price        NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    supplier     VARCHAR(255),
    location     VARCHAR(255),
    notes        TEXT,
    car_id       BIGINT REFERENCES car(id) ON DELETE SET NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_part_sku
    ON part (sku)
    WHERE sku IS NOT NULL;

CREATE INDEX ix_part_name
    ON part (name);

CREATE INDEX ix_part_category
    ON part (category);

CREATE INDEX ix_part_car_id
    ON part (car_id);

CREATE INDEX ix_part_stock_level
    ON part (quantity, min_quantity);

CREATE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_car_updated_at
    BEFORE UPDATE ON car
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_part_updated_at
    BEFORE UPDATE ON part
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

CREATE VIEW inventory AS
SELECT
    p.*,
    CASE
        WHEN p.quantity = 0 THEN 'out_of_stock'
        WHEN p.quantity <= p.min_quantity THEN 'low_stock'
        ELSE 'in_stock'
    END AS stock_status
FROM part AS p;
